export const scheduleData: Record<string, DaySchedule> = scheduleEvents.reduce(
  (acc, event) => {
    if (!acc[event.date]) acc[event.date] = { events: [] };
    acc[event.date].events.push(event);
    return acc;
  },
  {} as Record<string, DaySchedule>,
);

export function getScheduleEventCategory(event: ScheduleEvent) {
  if (event.label === "keynote") return "keynote" as const;
  if (event.type === "workshop") return "workshop" as const;
  if (event.type === "talk") return "talk" as const;
  return "other" as const;
}
